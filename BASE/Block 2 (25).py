    {'name': 'Иван', 'age': 21, 'grades': [5, 5, 5, 5]},
    {'name': 'Мария', 'age': 19, 'grades': [3, 4, 4, 3, 5]},
    {'name': 'Петр', 'age': 22, 'grades': [2, 3, 3, 4]},
    {'name': 'Елена', 'age': 20, 'grades': [5, 4, 5, 4, 5]},
    {'name': 'Дмитрий', 'age': 23, 'grades': [3, 3, 2]},
