def format_list(lst: list) -> str:
    """
    Форматирует строку из списка, добавляя "и" перед последним элементом.
    :param lst: Список элементов.
    :return: Отформатированная строка.
    """
    if len(lst) > 1:
        return ', '.join(lst[:-1]) + f' и {lst[-1]}'
    else:
        return lst[0]


