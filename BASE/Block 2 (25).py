def unique_preserve(lst: list) -> list:
    """
    Принимает список.
    Возвращает список из уникальных элементов с сохранением порядка.
    :param lst: Список для сортировки.
    :return: Новый список с уникальными элементами и сохранением порядка.
    """
    unique_list = []
    for item in lst:
        if item not in unique_list:
            unique_list.append(item)
    return unique_list


